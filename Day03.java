public class EscapeSequence {
    public static void main(String[] args) {
        //untuk menampilkan tanda kutip
        System.out.println("Halo saya \"Asep\"");

        //untuk menampilkan tanda blackslash (\)
        System.out.println("C:\\Users\\Java");

        //untuk menambahkan jarak antar kalimat
        System.out.println("Nama:\tMuh Asep");
        System.out.println("Umur:\t21 tahun");

        //untuk membuat baris selanjutnya
        System.out.println("\nFakultas:");
        System.out.println("Teknik");
        System.out.println("\nProdi:");
        System.out.println("Informatika");
    }
}
